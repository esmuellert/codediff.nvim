local h = require("tests.support.e2e")
local fixture = require("tests.fixtures.refresh_repo")

for _, backend in ipairs({ "native", "polling" }) do
  for _, layout in ipairs({ "side-by-side", "inline" }) do
    describe("History actions E2E / " .. backend .. " / " .. layout, function()
      local repo, screen
      before_each(function()
        repo = h.repo("history")
        screen = h.screen(backend, layout)
      end)
      after_each(function()
        h.close(screen, repo)
        screen, repo = nil, nil
      end)
      local function open(command)
        h.open(screen, repo, command or "CodeDiff history")
        h.expect_text(screen, "modified", "history-two")
        h.idle(screen)
      end

      it("[Y01] opens and expands the latest commit with its real file changes", function()
        open()
        h.expect_panel(screen, "history two")
        h.expect_panel(screen, "history one")
        h.expect_panel(screen, "b.txt")
        h.expect_panel(screen, "gone.txt")
        h.expect_panel(screen, "renamed file.txt")
        h.expect_text(screen, "original", "history-one")
        assert.equals("history-two", repo.blob_lines(repo.second, "a.txt")[2])
      end)

      it("[Y02] navigates files through deleted previews and back to two-sided comparisons", function()
        open()
        h.select(screen, "b.txt")
        h.expect_text(screen, "modified", "history-two-B")
        h.idle(screen)
        h.action(screen, "view", "next_file", "modified")
        h.expect_text(screen, "original", "delete body")
        h.idle(screen)
        h.action(screen, "view", "prev_file", "original")
        h.expect_text(screen, "modified", "history-two-B")
        h.expect_text(screen, "original", "base-B")
      end)

      it("[Y03] lazily expands an older commit and renders an added-file preview", function()
        open()
        h.panel_cursor(screen, "history one")
        h.feed(screen, "<CR>")
        h.expect_panel(screen, "added.txt")
        h.select(screen, "added.txt")
        h.expect_text(screen, "modified", "added in history")
        assert.equals("modified", screen:exec("return refresh_session().single_side"))
        assert.same({ "added in history" }, repo.blob_lines(repo.first, "history/added.txt"))
      end)

      it("[Y04] selecting an older file uses that commit's parent and not current HEAD", function()
        open()
        h.panel_cursor(screen, "history one")
        h.feed(screen, "<CR>")
        h.expect_panel(screen, "added.txt")
        h.panel_cursor(screen, "history one")
        h.feed(screen, "j<CR>")
        h.expect_text(screen, "original", "base-A")
        h.expect_text(screen, "modified", "history-one")
        assert.equals(repo.second, vim.trim(repo.command({ "rev-parse", "HEAD" })))
      end)

      it("[Y05] list/tree toggles retain expanded files and the selected comparison", function()
        open()
        h.focus(screen, "panel")
        local before, unchanged = h.panes(screen), h.watch_grid(screen)
        h.action(screen, "history", "toggle_view_mode")
        h.expect_panel(screen, "rename")
        h.expect_panel(screen, "renamed file.txt")
        h.action(screen, "history", "toggle_view_mode")
        h.expect_panel(screen, "b.txt")
        h.preserved(screen, before, 150)
        unchanged()
      end)

      it("[Y06] a new commit and manual R update the list without reopening history", function()
        open()
        h.focus(screen, "panel")
        local before = h.panes(screen)
        repo.replace("a.txt", 2, "history-three")
        repo.git("commit -am history-three")
        h.action(screen, "history", "refresh")
        h.expect_panel(screen, "history-three")
        h.preserved(screen, before, 150)
        h.expect_text(screen, "modified", "history-two")
      end)

      it("[Y07] single-file history navigates commits and reaches the parentless root", function()
        open("CodeDiff history %")
        h.action(screen, "view", "next_file", "modified")
        h.expect_text(screen, "modified", "history-one")
        h.idle(screen)
        h.action(screen, "view", "next_file", "modified")
        h.expect_lines(screen, "original", { "" })
        h.expect_text(screen, "modified", "base-A")
        h.idle(screen)
        h.action(screen, "view", "prev_file", "modified")
        h.expect_text(screen, "modified", "history-one")
      end)

      it("[Y08] follows a symbolic history base when its tag moves", function()
        open("CodeDiff history --base fixture/base")
        h.expect_text(screen, "original", "base-A")
        repo.command({ "tag", "-f", "fixture/base", repo.first })
        h.expect_text(screen, "original", "history-one")
        h.expect_text(screen, "modified", "history-two")
      end)

      it("[Y09] a collapsed commit remains collapsed after a refs refresh", function()
        open()
        h.panel_cursor(screen, "history two")
        h.feed(screen, "<CR>")
        h.expect_panel(screen, "b.txt", false)
        local before = h.panes(screen)
        local event = h.checkpoint(screen)
        repo.command({ "tag", "new-tag", repo.first })
        h.wait_event(screen, event)
        h.expect_panel(screen, "b.txt", false)
        h.preserved(screen, before, 100)
      end)

      it("[Y10] ignored files stay absent through tree mode and manual refresh", function()
        screen:exec("require('codediff').setup({ explorer = { file_filter = { ignore = { 'rename/**' } } } })")
        open()
        h.expect_panel(screen, "renamed file.txt", false)
        h.action(screen, "history", "toggle_view_mode", "panel")
        h.expect_panel(screen, "renamed file.txt", false)
        h.action(screen, "history", "refresh")
        h.idle(screen)
        h.expect_panel(screen, "renamed file.txt", false)
        h.expect_text(screen, "modified", "history-two")
      end)

      it("[Y11] renamed history files resolve both their old and new paths", function()
        open()
        h.select(screen, "gone.txt")
        h.expect_text(screen, "original", "delete body")
        h.idle(screen)
        h.select(screen, "renamed file.txt")
        h.expect_lines(screen, "original", fixture.files["rename/source file.txt"])
        h.expect_lines(screen, "modified", fixture.files["rename/source file.txt"])
        h.expect_text(screen, "modified", "rename body 2")
        assert.equals(0, vim.fn.filereadable(repo.path("rename/source file.txt")))
      end)

      it("[Y13] line-range history remains filtered after HEAD changes", function()
        h.open(screen, repo, "2,2CodeDiff history")
        h.expect_text(screen, "modified", "history-two")
        h.idle(screen)
        local event = h.checkpoint(screen)
        repo.replace("a.txt", 5, "unrelated tail edit")
        repo.git("commit -am history-unrelated")
        h.wait_event(screen, event)
        h.expect_panel(screen, "history-unrelated", false)
        h.expect_text(screen, "modified", "history-two")
      end)

      it("[Y14] reverse history opens the root commit and preserves ordering on refresh", function()
        h.open(screen, repo, "CodeDiff history --reverse")
        h.expect_text(screen, "modified", "base-A")
        h.idle(screen)
        h.panel_cursor(screen, "fixture base")
        h.feed(screen, "<CR>")
        local function ordered()
          local win = screen:exec("return refresh_session().panel.view.winid")
          local text = h.window_text(screen, win)
          local root, first, second = text:find("fixture base", 1, true), text:find("history one", 1, true), text:find("history two", 1, true)
          return root and first and second and root < first and first < second
        end
        screen:await(ordered, "reverse commit order was not rendered")
        repo.replace("a.txt", 2, "history-three")
        repo.git("commit -am history-three")
        h.expect_panel(screen, "history-three")
        screen:await(ordered, "refresh lost reverse commit ordering")
        h.expect_text(screen, "modified", "base-A")
      end)

      it("[Y12] layout changes retain a selected historical comparison", function()
        open()
        h.action(screen, "view", "toggle_layout", "modified")
        screen:await(function()
          return screen:exec("return refresh_session().layout ~= (...) and not refresh_session().refresh.loading", { layout })
        end)
        h.expect_text(screen, "modified", "history-two")
        h.expect_text(screen, "original", "history-one")
        assert.same({ "start", "history-two", "context", "end", "tail" }, h.panes(screen).modified.lines)
      end)
    end)
  end
end
